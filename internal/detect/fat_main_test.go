package detect

import (
	"fmt"
	"strings"
	"testing"

	"github.com/CaliLuke/lagotto/internal/audit"
)

func fatMainSource(functions int) string {
	source := "package main\nfunc main() {}\n"
	for i := 0; i < functions; i++ {
		source += fmt.Sprintf("func helper%d(n int) int { if n>0 { return n }; return 0 }\n", i)
	}
	return source + strings.Repeat("// authored documentation\n", 1000)
}

func TestFatMainReportsLogicAndHotspots(t *testing.T) {
	pkgs := fakeModule(t, map[string]string{"cmd/tool/main.go": fatMainSource(15), "internal/domain/domain.go": "package domain\ntype Domain struct{}"})
	findings := ScanFatMains(pkgs)
	if len(findings) != 1 || findings[0].SmellID != "G17" || findings[0].Severity != audit.SevLow {
		t.Fatalf("unexpected findings: %+v", findings)
	}
	evidence := findings[0].Evidence
	if evidence["function_count"] != 15 || evidence["has_internal"] != true {
		t.Fatalf("incorrect evidence: %+v", evidence)
	}
	hotspots := evidence["hotspots"].([]mainHotspot)
	if len(hotspots) != 5 || hotspots[0].Complexity != 2 || hotspots[0].Name != "helper0" {
		t.Fatalf("incorrect hotspots: %+v", hotspots)
	}
}

func TestFatMainTypesWithMethods(t *testing.T) {
	source := fatMainSource(0) + "type Store struct{}\nfunc (Store) Save() {}\ntype Server struct{}\nfunc (*Server) Serve() {}\ntype Handler[T any] struct{}\nfunc (Handler[T]) Handle() {}\n"
	findings := ScanFatMains(fakeModule(t, map[string]string{"main.go": source}))
	if len(findings) != 1 || findings[0].Evidence["types_with_methods"] != 3 {
		t.Fatalf("expected three method types: %+v", findings)
	}
}

func TestFatMainExemptionsAndStructuralFloor(t *testing.T) {
	cases := []struct{ name, path, source string }{
		{"small", "main.go", "package main\nfunc main() {}\nfunc run() {}\n"},
		{"large wiring", "main.go", fatMainSource(1)},
		{"generated", "main.go", "// Code generated by fixture. DO NOT EDIT.\n" + fatMainSource(20)},
		{"test only", "main_test.go", fatMainSource(20)},
		{"examples", "examples/tool/main.go", fatMainSource(20)},
		{"testdata", "testdata/tool/main.go", fatMainSource(20)},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := ScanFatMains(fakeModule(t, map[string]string{tc.path: tc.source})); len(got) != 0 {
				t.Fatalf("unexpected finding: %+v", got)
			}
		})
	}
}
