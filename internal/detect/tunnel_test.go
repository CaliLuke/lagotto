// TestG8_ReExportTunnel fires when a package's only role is to
// re-export names from a deeper package — a TypeScript "barrel"
// pattern that adds an indirection layer with no Go-side benefit.
func TestG8_ReExportTunnel(t *testing.T) {
	pkgs := fakeModule(t, map[string]string{
		"go.mod":         "module example.com/test\ngo 1.21\n",
		"inner/inner.go": "package inner\n\ntype Foo struct{ N int }\n\nvar Default = Foo{N: 1}\n\nfunc Hello() string { return \"hi\" }\n",
		"outer/outer.go": "package outer\n\nimport \"example.com/test/inner\"\n\ntype Foo = inner.Foo\n\nvar Default = inner.Default\n\nfunc Hello() string { return inner.Hello() }\n",
	})
	findings := ScanReExportTunnel(pkgs)
	if !containsID(findings, "G8") {
		t.Fatalf("expected G8, got %v", findingIDs(findings))
	}
	if !strings.Contains(findings[0].Location, "outer") {
		t.Errorf("expected outer package in location, got %s", findings[0].Location)
	}
}

