func TestGenericPackageUsesDeclaredNameAndReuse(t *testing.T) {
	pkgs := fakeModule(t, map[string]string{
		"capability/values.go": "package utils\nconst ( A=1; B=2; C=3; D=4; E=5; F=6; G=7; H=8; I=9; J=10 )\n",
		"one/one.go":           "package one\nimport u \"example.com/test/capability\"\nvar Value=u.A",
		"two/two.go":           "package two\nimport u \"example.com/test/capability\"\nvar Value=u.A",
		"three/three.go":       "package three\nimport u \"example.com/test/capability\"\nvar Value=u.A",
	})
	root := pkgs[0].Module.Dir
	findings := ScanGenericPackages(root, pkgs, collectPackageDirs(root, pkgs, nil))
	if len(findings) != 1 || findings[0].Severity != audit.SevMedium || findings[0].Location != "capability" {
		t.Fatalf("expected accumulation risk: %+v", findings)
	}
	ev := findings[0].Evidence
	if ev["kind"] != "package" || ev["exported_identifier_count"] != 10 || ev["importer_count"] != 3 {
		t.Fatalf("incorrect evidence: %+v", ev)
	}
}

func TestGenericPackageLowAndNegativeCases(t *testing.T) {
	pkgs := fakeModule(t, map[string]string{
		"generic/one.go":              "package common\nconst One=1",
		"utils/domain.go":             "package domain\nconst One=1",
		"models/model.go":             "package models\ntype User struct{}",
		"types/value.go":              "package types\ntype Value int",
		"generated/values.go":         "// Code generated by fixture. DO NOT EDIT.\npackage utils\nconst One=1",
		"internal/testutil/common.go": "package common\nconst One=1",
		"helpers/only_test.go":        "package helpers\nconst One=1",
	})
	root := pkgs[0].Module.Dir
	findings := ScanGenericPackages(root, pkgs, collectPackageDirs(root, pkgs, nil))
	if len(findings) != 1 || findings[0].Location != "generic" || findings[0].Severity != audit.SevLow {
		t.Fatalf("unexpected generic names: %+v", findings)
	}
}

func TestGenericPackageExcludesGeneratedExportsAndTestImporters(t *testing.T) {
	pkgs := fakeModule(t, map[string]string{
		"common/value.go":             "package common\nconst Value=1",
		"common/generated.go":         "// Code generated by fixture. DO NOT EDIT.\npackage common\nconst ( A=1; B=2; C=3; D=4; E=5; F=6; G=7; H=8; I=9; J=10 )",
		"internal/testutil/helper.go": "package testutil\nimport \"example.com/test/common\"\nvar Value=common.Value",
	})
	root := pkgs[0].Module.Dir
	findings := ScanGenericPackages(root, pkgs, collectPackageDirs(root, pkgs, nil))
	if len(findings) != 1 || findings[0].Evidence["exported_identifier_count"] != 1 || findings[0].Evidence["importer_count"] != 0 {
		t.Fatalf("incorrect authored counts: %+v", findings)
	}
}
