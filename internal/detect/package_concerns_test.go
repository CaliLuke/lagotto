func packageConcernFixture() map[string]string {
	padding := strings.Repeat("// authored source line\n", 270)
	return map[string]string{
		"pkg/core.go":         "package pkg\ntype Core struct{}\n",
		"pkg/runner.go":       "package pkg\nfunc Run() { langParse(Core{}) }\n",
		"pkg/lang_parse.go":   "package pkg\nfunc langParse(c Core) { langResolve(c) }\n" + padding,
		"pkg/lang_resolve.go": "package pkg\nfunc langResolve(c Core) { langEmit(c) }\n" + padding,
		"pkg/lang_emit.go":    "package pkg\nfunc langEmit(c Core) {}\n" + padding,
	}
}

func TestPackageConcernsNarrowAcyclicBoundary(t *testing.T) {
	pkgs := fakeModule(t, packageConcernFixture())
	findings := ScanPackageConcerns(pkgs)
	if len(findings) != 1 || findings[0].Location != "pkg" {
		t.Fatalf("expected one package concern: %+v", findings)
	}
	groups := findings[0].Evidence["groups"].([]packageConcern)
	if len(groups) != 1 || groups[0].Prefix != "lang" || len(groups[0].Files) != 3 || len(groups[0].Inbound) != 1 || groups[0].Inbound[0].From != "runner.go" || len(groups[0].Outbound) != 3 {
		t.Fatalf("incorrect boundary evidence: %+v", groups)
	}
}

func TestPackageConcernsRejectCoupledGroups(t *testing.T) {
	cases := []struct {
		name      string
		additions map[string]string
	}{
		{"many callers", map[string]string{"pkg/other.go": "package pkg\nfunc Other() { langParse(Core{}) }"}},
		{"direct cycle", map[string]string{"pkg/core.go": "package pkg\ntype Core struct{}\nfunc CoreRun() { langParse(Core{}) }", "pkg/runner.go": "package pkg\n"}},
		{"transitive cycle", map[string]string{"pkg/core.go": "package pkg\ntype Core struct{}\nfunc CoreRun() { Run() }"}},
		{"receiver split", map[string]string{"pkg/lang_emit.go": "package pkg\nfunc (c Core) Emit() {}\n" + strings.Repeat("// line\n", 270)}},
		{"interface split", map[string]string{"pkg/core.go": "package pkg\ntype Core struct{}\ntype Emitter interface { Emit() }\n", "pkg/lang_emit.go": "package pkg\ntype langEmitter struct{}\nfunc (langEmitter) Emit() {}\nfunc langEmit(c Core) {}\n" + strings.Repeat("// line\n", 270)}},
		{"small group", map[string]string{"pkg/lang_emit.go": "package pkg\nfunc langEmit(c Core) {}\n"}},
		{"generated caller", map[string]string{"pkg/generated.go": "// Code generated by fixture. DO NOT EDIT.\npackage pkg\nfunc Generated() { langParse(Core{}) }\n"}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			files := packageConcernFixture()
			for path, source := range tc.additions {
				files[path] = source
			}
			if findings := ScanPackageConcerns(fakeModule(t, files)); len(findings) != 0 {
				t.Fatalf("unexpected finding: %+v", findings)
			}
		})
	}
}

func TestPackageConcernsSkipMainAndTestHelpers(t *testing.T) {
	for _, kind := range []string{"main", "testutil", "generated"} {
		t.Run(kind, func(t *testing.T) {
			files := packageConcernFixture()
			for path, source := range files {
				switch kind {
				case "main":
					files[path] = strings.ReplaceAll(source, "package pkg", "package main")
				case "testutil":
					delete(files, path)
					files[strings.Replace(path, "pkg/", "testutil/", 1)] = source
				case "generated":
					files[path] = "// Code generated by fixture. DO NOT EDIT.\n" + source
				}
			}
			if findings := ScanPackageConcerns(fakeModule(t, files)); len(findings) != 0 {
				t.Fatalf("unexpected finding: %+v", findings)
			}
		})
	}
}

func TestPackageConcernsReplaceOnlyCoveredG9Prefixes(t *testing.T) {
	pkgs := fakeModule(t, packageConcernFixture())
	root := pkgs[0].Module.Dir
	groups := ScanPackageConcerns(pkgs)
	g9 := prefixClusterFindings("pkg", []string{"lang_parse.go", "lang_resolve.go", "lang_emit.go", "misc_one.go", "misc_two.go", "misc_three.go"})
	findings := removeCoveredPrefixClusters(root, append(g9, groups...))
	if len(findings) != 2 {
		t.Fatalf("expected G9 remainder and G16, got %+v", findings)
	}
	clusters := findings[0].Evidence["clusters"].([]prefixCluster)
	if len(clusters) != 1 || clusters[0].Prefix != "misc" {
		t.Fatalf("incorrect remainder: %+v", clusters)
	}
	subroot := filepath.Join(root, "pkg")
	only := prefixClusterFindings(".", []string{"lang_parse.go", "lang_resolve.go", "lang_emit.go"})
	if got := removeCoveredPrefixClusters(subroot, append(only, groups...)); len(got) != 1 || got[0].SmellID != "G16" {
		t.Fatalf("subdirectory overlap: %+v", got)
	}
	if _, _, err := audit.ApplySuppressions(findings, []string{"G9@pkg"}); err != nil {
		t.Fatal(err)
	}
}

func TestPackageConcernsDocumentationDoesNotCreateAnotherConcern(t *testing.T) {
	files := packageConcernFixture()
	delete(files, "pkg/core.go")
	delete(files, "pkg/runner.go")
	files["pkg/doc.go"] = "// Package pkg is one cohesive component.\npackage pkg\n"
	for path, source := range files {
		files[path] = strings.ReplaceAll(strings.ReplaceAll(source, "c Core", ""), "(c)", "()")
	}
	if got := ScanPackageConcerns(fakeModule(t, files)); len(got) != 0 {
		t.Fatalf("documentation creates false subset: %+v", got)
	}
}

func TestPackageConcernsRemoveOverlapForRelativeRoot(t *testing.T) {
	pkgs := fakeModule(t, packageConcernFixture())
	t.Chdir(pkgs[0].Module.Dir)
	groups := ScanPackageConcerns(pkgs)
	g9 := prefixClusterFindings("pkg", []string{"lang_parse.go", "lang_resolve.go", "lang_emit.go"})
	if got := removeCoveredPrefixClusters(".", append(g9, groups...)); len(got) != 1 || got[0].SmellID != "G16" {
		t.Fatalf("relative root overlap: %+v", got)
	}
	t.Chdir("pkg")
	g9 = prefixClusterFindings(".", []string{"lang_parse.go", "lang_resolve.go", "lang_emit.go"})
	if got := removeCoveredPrefixClusters(".", append(g9, groups...)); len(got) != 1 || got[0].SmellID != "G16" {
		t.Fatalf("relative subroot overlap: %+v", got)
	}
}
